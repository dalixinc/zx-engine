#!/usr/bin/env python3
"""
gfx2raw.py - unshifted masked rows, for a sprite the Z80 shifts itself.

Usage:  python3 tools/gfx2raw.py gfx/wheel-full.txt gfx/wheel_spin.asm wspin 2
        python3 tools/gfx2raw.py gfx/fish.txt gfx/fish_raw.asm fish 1
        python3 tools/gfx2raw.py gfx/wheel.txt gfx/wheel_raw.asm wheel 1

The last argument keeps every Nth frame (2 = frames 0, 2, 4, ...).

gfx2asm.py stores 8 pre-shifted copies of each frame, which is what the
draw wants, but it is 8 times the size. So for Atlantis the tape carries
only this: each row once, as

      db mask0, mask1, data0, data1

for a sprite up to 16 pixels wide (mask bit 1 = keep the background, data
bit 1 = ink, the leftmost pixel in bit 7 of byte 0, the bits past the
width kept as background). src/atlantis/preshift.asm makes the shifted
copies from it at start-up, byte for byte what gfx2asm.py writes, and
PRESHIFT_TABLES builds the same pointer tables.

The pictures are in gfx2asm.py's order, so its tables still index them:
  - art that is mirrored (the fish): every frame facing right, then
    every frame facing left;
  - "mirror off" art: each different picture once. If a picture comes
    back later in the animation (the pulsar), it is not stored again,
    and name_seq says which picture each step shows, as gfx2asm.py's
    does. Art with no repeats (the spinning wheel) has no name_seq here.

It also writes the sizes the code uses: NAME_WIDTH, NAME_HEIGHT,
NAME_FRAMES (animation steps), NAME_PICS (pictures stored), NAME_BYTES
(the widest shifted row), NAME_WIDE (the first shift that needs a third
byte) and, for a width that is not a multiple of 8, name_shift_bytes.
The art itself is a macro, NAME_ART, so it can be assembled somewhere
else than the sizes and name_seq: preshift reads it only at start-up.
"""
import sys

sys.path.insert(0, __file__.rsplit("/", 1)[0])
from gfx2asm import load_art, shifted_row, stored_bytes  # noqa: E402


def main():
    src, dst, name, step = sys.argv[1], sys.argv[2], sys.argv[3], int(sys.argv[4])
    frames, mirror = load_art(src)
    width = len(frames[0][0])
    if width > 16:
        sys.exit("gfx2raw: up to 16 pixels wide")
    kept = frames[::step]
    anim = len(kept)
    seq = None
    if mirror:
        pics = kept + [[r[::-1] for r in f] for f in kept]
        labels = [f"facing right, frame {i}" for i in range(anim)] + \
                 [f"facing left, frame {i}" for i in range(anim)]
    else:
        pics, order, seq = [], [], []
        for f in kept:
            key = tuple(f)
            if key not in order:
                order.append(key)
                pics.append(f)
            seq.append(order.index(key))
        labels = [f"picture {i}" for i in range(len(pics))]
        if seq == list(range(len(pics))):
            seq = None          # every step its own picture
    widths = [stored_bytes(width, s) for s in range(8)]
    wide = next((s for s in range(8) if widths[s] == 3), 8)
    if any(w != (3 if s >= wide else 2) for s, w in enumerate(widths)):
        sys.exit("gfx2raw: preshift.asm writes 2 bytes a row, then 3 from one shift on")
    up = name.upper()
    out = [
        f"; {dst} - GENERATED by tools/gfx2raw.py from {src}. Do not edit;",
        ";   edit the .txt and run make.",
        ";",
        f"; Every {step}th frame of the art, unshifted. Each row:" if step > 1
        else "; The art unshifted. Each row:",
        ";   db mask0, mask1, data0, data1",
        "; src/atlantis/preshift.asm makes the 8 shifted copies at start-up.",
        "",
        f"{up}_WIDTH   equ {width}",
        f"{up}_HEIGHT  equ {len(kept[0])}",
        f"{up}_FRAMES  equ {anim}",
        f"{up}_PICS    equ {len(pics)}",
        f"{up}_BYTES   equ {max(widths)}",
        f"{up}_WIDE    equ {wide}",
        "",
    ]
    if seq is not None:
        out += [f"; {name}_seq - which picture each step of the animation shows.",
                f"{up}_SHAPES  equ {len(pics)}",
                f"{name}_seq:",
                "        db " + ", ".join(str(n) for n in seq),
                ""]
    if width % 8:
        out += [f"; {name}_shift_bytes - how many bytes one row occupies at each",
                "; pixel shift. The background record is sized for the widest.",
                "; Assembled only if something reads it.",
                f"        IFUSED {name}_shift_bytes",
                f"{name}_shift_bytes:",
                "        db " + ", ".join(str(n) for n in widths),
                "        ENDIF",
                ""]
    out += [f"; {up}_ART - the art itself. Only preshift reads it, once, at start-up,",
            "; so main.asm puts it in the cold block, not with the data.",
            f"        MACRO {up}_ART",
            f"{name}_src:"]
    for i, frame in enumerate(pics):
        out.append(f"        ; {labels[i]}" + (f" (art frame {i * step})" if step > 1 else ""))
        for row in frame:
            mask, data = shifted_row(row, 0, 2)
            out.append(f"        db %{mask[0]:08b},%{mask[1]:08b}, "
                       f"%{data[0]:08b},%{data[1]:08b}  ; {row}")
    out += ["        ENDM", ""]
    open(dst, "w").write("\n".join(out))
    print(f"{dst}: {len(pics)} pictures, {len(pics) * len(pics[0]) * 4} bytes unshifted")


if __name__ == "__main__":
    main()
