#!/usr/bin/env python3
"""
gfx2asm.py - turn an ASCII-art sprite into pre-shifted, masked Z80 data.

Usage:  python3 tools/gfx2asm.py gfx/fish.txt gfx/fish.asm fish

Sprite width is taken from the art itself (the length of the first row).
The fish is 16 and the diver is 24, both multiples of 8. The wheel bomb
is 12, which is not.

WHY PRE-SHIFT AT BUILD TIME?
  The Spectrum screen is byte-addressed: one byte = 8 horizontal pixels. To
  draw a sprite at x = 13 we must shift every byte right by 13 & 7 = 5 bits.
  Shifting at run time costs ~8 T-states per bit per byte, every frame.
  Instead we store 8 copies of each frame, already shifted by 0..7 pixels.

WHY ONE EXTRA BYTE PER ROW, WHEN THE WIDTH IS A MULTIPLE OF 8?
  A sprite W pixels wide covers exactly W/8 bytes only when shift = 0. Shift
  it right by 1..7 and its rightmost pixels spill into the next byte along,
  so every shifted copy is W/8 + 1 bytes wide (16 px -> 3 bytes, 24 px -> 4).
  At shift 0 that last byte is simply empty (mask all 1s, data 0), but we
  store it anyway so that every copy has the same size and the Z80 drawing
  loop never needs to care which shift it is drawing.

  A width that is not a multiple of 8 does not need that spare byte on every
  shift. A 12-pixel row plus a shift of 0..4 still fits in 16 bits (2 bytes).
  A shift of 5..7 spills into a third byte (12 + 7 = 19 bits). Those copies
  are stored at their own width, and a small table (name_shift_bytes) tells
  the drawing code how many bytes that shift occupies. The fish and the
  diver do not use the table: their output is the same as it was when every
  width had to be a multiple of 8.

  We do it here in Python, rather than with a Z80 routine at start-up,
  because it is easier to read and check, costs no Z80 code, and lets the
  generated .asm show every row in binary so you can SEE the shifting.
  The cost is memory: see the size summary printed at the end.

OUTPUT FORMAT (per frame, per shift, per pixel row):
      db mask0,data0, mask1,data1, mask2,data2
  Mask bit 1 = keep the background pixel, 0 = sprite covers it.
  Data bit 1 = ink. The draw routine does:  screen = (screen AND mask) OR data
"""
import sys



def load_art(path):
    """Read the art.

    Returns (frames, mirror). frames is a list of frames, each a list of
    row strings. mirror is False when the file says "mirror off": the
    wheel bomb's T must not be flipped, so it has no left-facing copy.
    Anything else (the fish, the diver) is mirrored, as before.
    """
    frames, cur = [], None
    width = None
    mirror = True
    for line in open(path):
        line = line.rstrip("\n")
        if not line or line.startswith(";"):
            continue
        if line.strip() == "mirror off":
            mirror = False
            continue
        if line.startswith("frame"):
            cur = []
            frames.append(cur)
            continue
        if width is None:
            width = len(line)
            if width < 1:
                sys.exit(f"sprite width must be at least 1, got {width}")
        if len(line) != width or set(line) - set("#-."):
            sys.exit(f"bad sprite row (need {width} chars of # - .): {line!r}")
        cur.append(line)
    heights = {len(f) for f in frames}
    if len(heights) != 1:
        sys.exit("all frames must have the same height")
    return frames, mirror


def load_frames(path):
    """Frames only. tools/make-diver-montage.py imports this."""
    frames, _mirror = load_art(path)
    return frames


def row_bits(row):
    """Return (data, opaque) as ints, leftmost pixel = highest bit."""
    data = opaque = 0
    for ch in row:
        data = (data << 1) | (ch == "#")
        opaque = (opaque << 1) | (ch in "#-")
    return data, opaque


def stored_bytes(width, shift):
    """How many bytes a shifted row occupies.

    A multiple of 8 always uses width/8 + 1, including the empty byte at
    shift 0, so every copy is the same size. Anything else uses only the
    bytes the pixels actually touch: (width + shift + 7) // 8.
    """
    if width % 8 == 0:
        return width // 8 + 1
    return (width + shift + 7) // 8


def shifted_row(row, shift, nbytes):
    """Shift a row right by `shift` into a field of `nbytes` bytes.

    The row is lined up at the left, then moved right by `shift`, which
    leaves `shift` empty bits on the left and any spare bits on the right.
    Returns (mask bytes, data bytes), leftmost byte first.

    For a width that is a multiple of 8, nbytes is width/8 + 1 and the
    shift amount is 8 - shift, which is what the fish and the diver were
    built with. Do not change that: their generated bytes are checked
    against the frozen Engine Demo 1 tape.
    """
    data, opaque = row_bits(row)
    width = len(row)
    bits = nbytes * 8
    shl = bits - width - shift
    data_f = data << shl
    mask_f = ~(opaque << shl) & ((1 << bits) - 1)
    positions = range(bits - 8, -1, -8)     # byte 0 = top 8 bits
    return ([(mask_f >> p) & 0xFF for p in positions],
            [(data_f >> p) & 0xFF for p in positions])


def main():
    src, dst, name = sys.argv[1], sys.argv[2], sys.argv[3]
    frames, mirror = load_art(src)
    height = len(frames[0])
    width = len(frames[0][0])
    # One width for every shift when the art fills whole bytes. The fish
    # and the diver take this path, and the text below is the text their
    # committed files already have.
    fixed = width % 8 == 0
    if fixed:
        nbytes = width // 8 + 1
        shift_widths = [nbytes] * 8
    else:
        shift_widths = [stored_bytes(width, s) for s in range(8)]
        nbytes = max(shift_widths)
    anim_len = len(frames)
    # Same picture stored once. The sequence is which shape each step
    # of the animation shows. Mirrored sprites (fish, diver) skip this:
    # their bytes are the ones Engine Demo 1 was built with.
    seq = None
    if not mirror:
        order = []
        seq = []
        uniq = []
        for fr in frames:
            key = tuple(fr)
            if key not in order:
                order.append(key)
                uniq.append(fr)
            seq.append(order.index(key))
        frames = uniq
    if mirror:
        facings = [("right", frames),
                   ("left", [[r[::-1] for r in f] for f in frames])]
    else:
        # One facing. Index in the image table is the shape number.
        facings = [("right", frames)]

    out = []
    w = out.append
    w(f"; {dst} - GENERATED by tools/gfx2asm.py from {src}. Do not edit;")
    w(";   edit the .txt and run make (or python3 tools/gfx2asm.py ...).")
    w(";")
    if fixed:
        w(f"; Each row: db mask,data x {nbytes} bytes. mask 1 = keep background, data 1 = ink.")
        w("; The comment shows the shifted row: # ink, - paper (opaque), . see-through")
    else:
        w("; Each row: db mask,data, repeated across that shift's own width.")
        w("; mask 1 = keep background, data 1 = ink.")
        w("; The comment shows the shifted row: # ink, - paper (opaque), . see-through")
        listed = ", ".join(str(n) for n in shift_widths)
        w(f"; Bytes per shift 0..7: {listed}")
    w("")
    w(f"{name.upper()}_WIDTH  equ {width}       ; pixels, as drawn")
    if fixed:
        w(f"{name.upper()}_BYTES  equ {nbytes}        ; bytes per row once shifted (width/8 + 1)")
    else:
        w(f"{name.upper()}_BYTES  equ {nbytes}        ; widest shifted row (see {name}_shift_bytes)")
    w(f"{name.upper()}_HEIGHT equ {height}")
    if seq is None:
        w(f"{name.upper()}_FRAMES equ {len(frames)}")
    else:
        # FRAMES is the animation, not the number of stored pictures.
        w(f"{name.upper()}_FRAMES equ {anim_len}")
        w(f"{name.upper()}_SHAPES equ {len(frames)}")
    w("")
    if seq is not None:
        w(f"; {name}_seq - one byte per animation step. The byte is the")
        w("; shape number in the image table. A repeated step does not")
        w("; store the picture again.")
        w(f"{name}_seq:")
        w("        db " + ", ".join(str(n) for n in seq))
        w("")
    if not fixed:
        w(f"; {name}_shift_bytes - how many bytes one row occupies at each")
        w("; pixel shift. The background record is sized for the widest.")
        w(f"{name}_shift_bytes:")
        w("        db " + ", ".join(str(n) for n in shift_widths))
        w("")
    if seq is None:
        w(f"; {name}_images: one entry per (facing, frame); each points to a table of")
        w(";   8 pointers, one per pixel shift 0..7. Index = facing*FRAMES + frame.")
    else:
        w(f"; {name}_images: one entry per stored shape. {name}_seq picks which.")
        w("; Each entry points to a table of 8 pointers, one per pixel shift.")
    w(f"{name}_images:")
    for face, fr in facings:
        for i in range(len(fr)):
            w(f"        dw {name}_{face}_f{i}")
    w("")
    for face, fr in facings:
        for i, f in enumerate(fr):
            w(f"{name}_{face}_f{i}:")
            w("        dw " + ", ".join(f"{name}_{face}_f{i}_s{s}" for s in range(8)))
    total = 0
    for face, fr in facings:
        for i, f in enumerate(fr):
            for s in range(8):
                row_bytes = shift_widths[s]
                w("")
                w(f"{name}_{face}_f{i}_s{s}:  ; facing {face}, frame {i}, shifted right {s}")
                for row in f:
                    m, d = shifted_row(row, s, row_bytes)
                    pairs = ", ".join(f"%{a:08b},%{b:08b}" for a, b in zip(m, d))
                    pad = row_bytes * 8 - width - s
                    picture = ("." * s + row + "." * pad)
                    w(f"        db {pairs}  ; {picture}")
                    total += 2 * row_bytes
    w("")
    if fixed:
        w(f"; total image bytes: {total}  ({len(facings)} facings x {len(frames)} frames"
          f" x 8 shifts x {height} rows x {2*nbytes} bytes)")
    else:
        kind = "shapes" if seq is not None else "frames"
        w(f"; total image bytes: {total}  ({len(facings)} facings x {len(frames)} {kind}"
          f" x 8 shifts, width depending on the shift)")
    open(dst, "w").write("\n".join(out) + "\n")
    print(f"{dst}: {total} bytes of sprite data")


if __name__ == "__main__":
    main()
