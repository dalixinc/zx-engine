#!/usr/bin/env python3
"""
gfx2asm.py - turn an ASCII-art sprite into pre-shifted, masked Z80 data.

Usage:  python3 tools/gfx2asm.py gfx/fish.txt gfx/fish.asm fish

Sprite width: any multiple of 8 pixels (the fish is 16, the diver 24). It is
taken from the art itself (the length of the first row).

WHY PRE-SHIFT AT BUILD TIME?
  The Spectrum screen is byte-addressed: one byte = 8 horizontal pixels. To
  draw a sprite at x = 13 we must shift every byte right by 13 & 7 = 5 bits.
  Shifting at run time costs ~8 T-states per bit per byte, every frame.
  Instead we store 8 copies of each frame, already shifted by 0..7 pixels.

WHY ONE EXTRA BYTE PER ROW?
  A sprite W pixels wide covers exactly W/8 bytes only when shift = 0. Shift
  it right by 1..7 and its rightmost pixels spill into the next byte along,
  so every shifted copy is W/8 + 1 bytes wide (16 px -> 3 bytes, 24 px -> 4).
  At shift 0 that last byte is simply empty (mask all 1s, data 0), but we
  store it anyway so that every copy has the same size and the Z80 drawing
  loop never needs to care which shift it is drawing.

  We do it here in Python, rather than with a Z80 routine at start-up,
  because it is easier to read and check, costs no Z80 code, and lets the
  generated .asm show every row in binary so you can SEE the shifting.
  The cost is memory: see the size summary printed at the end.

OUTPUT FORMAT (per frame, per shift, per pixel row):
      db mask0,data0, mask1,data1, mask2,data2
  Mask bit 1 = keep the background pixel, 0 = sprite covers it.
  Data bit 1 = ink. The draw routine does:  screen = (screen AND mask) OR data
"""
import sys



def load_art(path):
    """Read the art.

    Returns (frames, mirror). frames is a list of frames, each a list of
    row strings. mirror is False when the file says "mirror off": the
    wheel bomb's T must not be flipped, so it has no left-facing copy.
    Anything else (the fish, the diver) is mirrored, as before.
    """
    frames, cur = [], None
    width = None
    mirror = True
    for line in open(path):
        line = line.rstrip("\n")
        if not line or line.startswith(";"):
            continue
        if line.strip() == "mirror off":
            mirror = False
            continue
        if line.startswith("frame"):
            cur = []
            frames.append(cur)
            continue
        if width is None:
            width = len(line)
            if width % 8:
                sys.exit(f"sprite width must be a multiple of 8, got {width}")
        if len(line) != width or set(line) - set("#-."):
            sys.exit(f"bad sprite row (need {width} chars of # - .): {line!r}")
        cur.append(line)
    heights = {len(f) for f in frames}
    if len(heights) != 1:
        sys.exit("all frames must have the same height")
    return frames, mirror


def load_frames(path):
    """Frames only. tools/make-diver-montage.py imports this."""
    frames, _mirror = load_art(path)
    return frames


def row_bits(row):
    """Return (data, opaque) as ints, leftmost pixel = highest bit."""
    data = opaque = 0
    for ch in row:
        data = (data << 1) | (ch == "#")
        opaque = (opaque << 1) | (ch in "#-")
    return data, opaque


def shifted_row(row, shift):
    """Shift a W-pixel row right by `shift` into a field of W/8 + 1 bytes.

    Returns (mask bytes, data bytes), leftmost byte first."""
    data, opaque = row_bits(row)
    nbytes = len(row) // 8 + 1
    bits = nbytes * 8
    # Line the row up at the left of the wider field (shift 0 leaves the
    # spare byte empty on the right), then move it right by `shift`.
    data_f = data << (8 - shift)
    mask_f = ~(opaque << (8 - shift)) & ((1 << bits) - 1)
    positions = range(bits - 8, -1, -8)     # byte 0 = top 8 bits
    return ([(mask_f >> p) & 0xFF for p in positions],
            [(data_f >> p) & 0xFF for p in positions])


def main():
    src, dst, name = sys.argv[1], sys.argv[2], sys.argv[3]
    frames, mirror = load_art(src)
    height = len(frames[0])
    width = len(frames[0][0])
    nbytes = width // 8 + 1
    if mirror:
        facings = [("right", frames),
                   ("left", [[r[::-1] for r in f] for f in frames])]
    else:
        # One facing. Index in the image table is just the frame number.
        facings = [("right", frames)]

    out = []
    w = out.append
    w(f"; {dst} - GENERATED by tools/gfx2asm.py from {src}. Do not edit;")
    w(";   edit the .txt and run make (or python3 tools/gfx2asm.py ...).")
    w(";")
    w(f"; Each row: db mask,data x {nbytes} bytes. mask 1 = keep background, data 1 = ink.")
    w("; The comment shows the shifted row: # ink, - paper (opaque), . see-through")
    w("")
    w(f"{name.upper()}_WIDTH  equ {width}       ; pixels, as drawn")
    w(f"{name.upper()}_BYTES  equ {nbytes}        ; bytes per row once shifted (width/8 + 1)")
    w(f"{name.upper()}_HEIGHT equ {height}")
    w(f"{name.upper()}_FRAMES equ {len(frames)}")
    w("")
    w(f"; {name}_images: one entry per (facing, frame); each points to a table of")
    w(";   8 pointers, one per pixel shift 0..7. Index = facing*FRAMES + frame.")
    w(f"{name}_images:")
    for face, fr in facings:
        for i in range(len(fr)):
            w(f"        dw {name}_{face}_f{i}")
    w("")
    for face, fr in facings:
        for i, f in enumerate(fr):
            w(f"{name}_{face}_f{i}:")
            w("        dw " + ", ".join(f"{name}_{face}_f{i}_s{s}" for s in range(8)))
    total = 0
    for face, fr in facings:
        for i, f in enumerate(fr):
            for s in range(8):
                w("")
                w(f"{name}_{face}_f{i}_s{s}:  ; facing {face}, frame {i}, shifted right {s}")
                for row in f:
                    m, d = shifted_row(row, s)
                    pairs = ", ".join(f"%{a:08b},%{b:08b}" for a, b in zip(m, d))
                    picture = ("." * s + row + "." * (8 - s))
                    w(f"        db {pairs}  ; {picture}")
                    total += 2 * nbytes
    w("")
    w(f"; total image bytes: {total}  ({len(facings)} facings x {len(frames)} frames"
      f" x 8 shifts x {height} rows x {2*nbytes} bytes)")
    open(dst, "w").write("\n".join(out) + "\n")
    print(f"{dst}: {total} bytes of sprite data")


if __name__ == "__main__":
    main()
